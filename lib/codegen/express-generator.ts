import type { Project, Endpoint } from "@/db/schema";
import type { CachedRoute } from "@/lib/cache";

export interface CodeGenContext {
  project: Project;
  endpoints: (Endpoint & { routes: CachedRoute[] })[];
}

export interface GeneratedFile {
  path: string;
  content: string;
}

export function generateExpressProject(
  context: CodeGenContext,
): GeneratedFile[] {
  const files: GeneratedFile[] = [];

  // 1. package.json
  files.push({
    path: "package.json",
    content: JSON.stringify(
      {
        name: context.project.slug || "fack-api-generated",
        version: "1.0.0",
        description: context.project.description || "Generated by Fack API",
        main: "dist/index.js",
        scripts: {
          start: "node dist/index.js",
          build: "tsc",
          dev: "ts-node src/index.ts",
        },
        dependencies: {
          express: "^4.19.2",
          cors: "^2.8.5",
          dotenv: "^16.4.5",
          zod: "^3.23.8",
        },
        devDependencies: {
          "@types/cors": "^2.8.17",
          "@types/express": "^4.17.21",
          "@types/node": "^20.12.7",
          "ts-node": "^10.9.2",
          typescript: "^5.4.5",
        },
      },
      null,
      2,
    ),
  });

  // 2. tsconfig.json
  files.push({
    path: "tsconfig.json",
    content: JSON.stringify(
      {
        compilerOptions: {
          target: "es2022",
          module: "commonjs",
          rootDir: "./src",
          outDir: "./dist",
          esModuleInterop: true,
          forceConsistentCasingInFileNames: true,
          strict: true,
          skipLibCheck: true,
        },
        include: ["src/**/*"],
      },
      null,
      2,
    ),
  });

  // 3. src/index.ts
  const indexTsContent = `import express from 'express';
import cors from 'cors';
import dotenv from 'dotenv';
${context.endpoints
  .map((ep, i) => `import endpoint${i}Router from './routes/${ep.id}';`)
  .join("\n")}

dotenv.config();

const app = express();
const port = process.env.PORT || 3000;

app.use(cors());
app.use(express.json());

// Routes
${context.endpoints
  .map((ep, i) => `app.use('${ep.basePath}', endpoint${i}Router);`)
  .join("\n")}

app.get('/health', (req, res) => {
  res.json({ status: 'ok', project: '${context.project.name}' });
});

app.listen(port, () => {
  console.log(\`Server running at http://localhost:\${port}\`);
});
`;
  files.push({ path: "src/index.ts", content: indexTsContent });

  // 4. Routes
  context.endpoints.forEach((ep) => {
    let routeContent = `import { Router } from 'express';\n`;
    routeContent += `const router = Router();\n\n`;

    ep.routes.forEach((route) => {
      if (!route.isEnabled) return;

      const method = route.method.toLowerCase();
      // Express dynamic params use :param instead of {param}
      const expressPath = route.path.replace(/\{([^}]+)\}/g, ":$1");

      let handlerBody = `  // TODO: Implement actual logic\n`;
      const statusCode = route.statusCode || 200;

      let mockDataStr = "{}";
      if (route.responseTemplate && route.responseTemplate.trim() !== "") {
        // Just return the raw string template if they have one (without evaluating handlebars)
        mockDataStr = JSON.stringify({
          message: "Raw template mock",
          template: route.responseTemplate,
        });
      } else if (route.responseSchema && route.responseSchema.trim() !== "{}") {
        try {
          const parsed = JSON.parse(route.responseSchema);
          // Generate a basic scaffold of the mock
          if (parsed.type === "array") {
            mockDataStr = "[]";
          } else {
            mockDataStr = JSON.stringify(parsed.properties || {}, null, 2);
          }
        } catch {
          mockDataStr = "{}";
        }
      }

      handlerBody += `  res.status(${statusCode}).json(${mockDataStr});\n`;

      routeContent += `// ${route.method} ${ep.basePath}${route.path}\n`;
      if (route.isAuthRequired) {
        routeContent += `// Note: Auth Required\n`;
      }
      routeContent += `router.${method}('${expressPath}', async (req, res) => {\n`;
      routeContent += handlerBody;
      routeContent += `});\n\n`;
    });

    routeContent += `export default router;\n`;
    files.push({ path: `src/routes/${ep.id}.ts`, content: routeContent });
  });

  return files;
}
