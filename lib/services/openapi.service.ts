import { ProjectWithHierarchy } from "@/lib/services/project.service";

/**
 * Generates an OpenAPI 3.0.3 compliant JSON document for a given project.
 */
export function generateOpenApi(
  project: ProjectWithHierarchy,
): Record<string, any> {
  const openApi: Record<string, any> = {
    openapi: "3.0.3",
    info: {
      title: project.name,
      description: project.description || "Generated by Fack AI API Architect",
      version: "1.0.0",
    },
    paths: {},
  };

  for (const endpoint of project.endpoints) {
    for (const route of endpoint.routes) {
      // Normalize path to have a leading slash
      const basePath = endpoint.basePath.startsWith("/")
        ? endpoint.basePath
        : `/${endpoint.basePath}`;
      const routePath = route.path.startsWith("/")
        ? route.path
        : `/${route.path}`;
      let fullPath = `${basePath}${routePath}`.replace(/\/+/g, "/"); // remove double slashes
      if (fullPath !== "/") {
        fullPath = fullPath.replace(/\/$/, ""); // remove trailing slash
      }

      // Identify OpenAPI path parameters (e.g. /users/:id -> /users/{id})
      const openApiPath = fullPath.replace(/:([a-zA-Z0-9_]+)/g, "{$1}");

      const method = route.method.toLowerCase();

      // Parse responseSchema if possible

      let responseSchemaObj: Record<string, any> = {
        type: "object",
      };

      if (route.responseSchema) {
        try {
          const parsed = JSON.parse(route.responseSchema);
          if (parsed && typeof parsed === "object") {
            responseSchemaObj = parsed;
          }
        } catch {
          // fallback to empty object if unparseable
        }
      }

      if (!openApi.paths[openApiPath]) {
        openApi.paths[openApiPath] = {};
      }

      // Extract path parameters array for OpenAPI
      const pathParams = Array.from(
        openApiPath.matchAll(/\{([a-zA-Z0-9_]+)\}/g),
      ).map((match) => ({
        name: match[1],
        in: "path",
        required: true,
        schema: {
          type: "string",
        },
      }));

      openApi.paths[openApiPath][method] = {
        summary: `${route.method} ${openApiPath}`,
        tags: [endpoint.name],
        ...(pathParams.length > 0 ? { parameters: pathParams } : {}),
        responses: {
          [route.statusCode.toString()]: {
            description: `Response for ${route.statusCode}`,
            content: {
              "application/json": {
                schema: responseSchemaObj,
              },
            },
          },
        },
      };
    }
  }

  return openApi;
}
